#!/usr/bin/env bash
# Regenerate src/lib/database.types.ts (the `takt_student` schema) with
# cbra-platform's generator, from the local stack. Run after a migration there
# changes `takt_student`.
#
# cbra-platform's `db:types` names the `takt` schema only, so this calls the
# same generator (its pinned Supabase CLI, --local) with the student schema.
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
PLATFORM="$("$HERE/scripts/platform.sh")"
OUT="$HERE/src/lib/database.types.ts"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT
{
  echo "// Generated by scripts/db-types.sh (cbra-platform's Supabase CLI) from the local database. Do not edit."
  "$PLATFORM/scripts/db/supabase.sh" gen types typescript --local --schema takt_student
} > "$TMP"
mv "$TMP" "$OUT"
trap - EXIT
echo "wrote $OUT"
